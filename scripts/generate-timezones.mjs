import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const sourcePath = process.argv[2] ?? '/usr/share/zoneinfo/zone.tab';
const outputPath = new URL('../src/timezones/generated.ts', import.meta.url);
const source = readFileSync(sourcePath, 'utf8');
const ids = source
  .split(/\r?\n/)
  .filter((line) => line && !line.startsWith('#'))
  .map((line) => line.split('\t')[2])
  .filter((id) => typeof id === 'string')
  .sort((a, b) => a.localeCompare(b, 'en'));

if (ids.length < 400 || new Set(ids).size !== ids.length) {
  throw new Error(`Unexpected timezone catalog from ${sourcePath}: ${ids.length} entries`);
}

const body = `// Generated by scripts/generate-timezones.mjs from the IANA tzdata zone.tab installed on the build host.\n// Do not edit by hand. tzdata is public-domain data; see /usr/share/zoneinfo/zone.tab comments.\nexport const GENERATED_TIMEZONE_IDS = ${JSON.stringify(ids, null, 2)} as const;\n`;
mkdirSync(new URL('../src/timezones/', import.meta.url), { recursive: true });
writeFileSync(outputPath, body);
console.log(`Wrote ${ids.length} canonical timezone IDs to ${outputPath.pathname}`);
